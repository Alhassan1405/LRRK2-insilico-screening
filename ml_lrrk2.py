def compute_mordred(smiles):
    mol = Chem.MolFromSmiles(smiles)
    if mol is None:
        return None  # invalid molecule
    try:
        desc = calc(mol)
        desc_dict = desc.asdict()
        return desc_dict
    except Exception as e:
        print(f"Error for molecule {smiles}: {e}")
        return None

results = Parallel(n_jobs=-1)(delayed(compute_mordred)(smiles) for smiles in tqdm(data['Ligand SMILES']))


desc_df = pd.DataFrame([r for r in results if r is not None])


