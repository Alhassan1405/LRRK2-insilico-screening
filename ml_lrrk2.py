def load_mols(path):
    df = pd.read_csv(path)
    mols = [Chem.MolFromSmiles(str(s)) for s in df["Ligand SMILES"]]
    return [m for m in mols if m is not None]

def props(mols):
    return pd.DataFrame({
        "MW":   [Descriptors.MolWt(m) for m in mols],
        "LogP": [Crippen.MolLogP(m) for m in mols],
        "TPSA": [rdMolDescriptors.CalcTPSA(m) for m in mols],
        "HBA":  [rdMolDescriptors.CalcNumHBA(m) for m in mols],
        "HBD":  [rdMolDescriptors.CalcNumHBD(m) for m in mols],
        "RotB": [rdMolDescriptors.CalcNumRotatableBonds(m) for m in mols],
    })

